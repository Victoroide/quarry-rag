CREATE TABLE grant_catalog_assigned_incarnations (
    document_id UUID,
    incarnation UUID,
    PRIMARY KEY (document_id, incarnation)
);

CREATE TABLE grant_catalog_document_ownership (
    document_id UUID PRIMARY KEY,
    incarnation UUID NOT NULL,
    tenant_id UUID NOT NULL,
    principal_id UUID NOT NULL,
    collection TEXT COLLATE "C" NOT NULL,
    source_version TEXT NOT NULL CHECK (source_version ~ '^[0-9a-f]{64}$'),
    ready BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (tenant_id, document_id, incarnation),
    FOREIGN KEY (tenant_id, principal_id) REFERENCES grant_catalog_principals (tenant_id, principal_id),
    FOREIGN KEY (tenant_id, collection) REFERENCES grant_catalog_collections,
    FOREIGN KEY (document_id, incarnation) REFERENCES grant_catalog_assigned_incarnations
