CREATE TABLE grant_catalog_document_grants (
    tenant_id UUID NOT NULL,
    document_id UUID NOT NULL,
    incarnation UUID NOT NULL,
    principal_id UUID NOT NULL,
    can_read BOOLEAN NOT NULL,
    can_download BOOLEAN NOT NULL CHECK (NOT can_download OR can_read),
    PRIMARY KEY (tenant_id, document_id, incarnation, principal_id),
    FOREIGN KEY (tenant_id, document_id, incarnation) REFERENCES grant_catalog_document_ownership
        (tenant_id, document_id, incarnation) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, principal_id) REFERENCES grant_catalog_principals (tenant_id, principal_id)
);

CREATE TABLE grant_catalog_document_reservations (
    document_id UUID PRIMARY KEY,
    incarnation UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE CHECK (incarnation <> document_id),
    tenant_id UUID NOT NULL,
    principal_id UUID NOT NULL,
    collection TEXT COLLATE "C" NOT NULL,
    state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'spent', 'superseded')),
    FOREIGN KEY (tenant_id, principal_id) REFERENCES grant_catalog_principals (tenant_id, principal_id),
    FOREIGN KEY (tenant_id, collection) REFERENCES grant_catalog_collections
);

CREATE TABLE grant_catalog_policy_audit (
    revision BIGINT PRIMARY KEY,
    operator NAME NOT NULL,
    batch_id UUID UNIQUE,
    payload_hash BYTEA,
    document_id UUID,
    incarnation UUID,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK ((batch_id IS NOT NULL AND payload_hash IS NOT NULL AND document_id IS NULL AND incarnation IS NULL)
        OR (batch_id IS NULL AND payload_hash IS NULL AND document_id IS NOT NULL AND incarnation IS NOT NULL))
