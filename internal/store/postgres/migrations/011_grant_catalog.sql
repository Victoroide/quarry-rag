CREATE FUNCTION grant_catalog_keep_document_identity() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF (OLD.id, OLD.incarnation) IS DISTINCT FROM (NEW.id, NEW.incarnation) THEN
        RAISE check_violation USING MESSAGE = 'document identity is immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER keep_document_identity BEFORE UPDATE OF id, incarnation ON documents
    FOR EACH ROW EXECUTE FUNCTION grant_catalog_keep_document_identity();

CREATE FUNCTION grant_catalog_guard_assignment_marker() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    owns_incarnation BOOLEAN;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.grant_catalog_assigned THEN
        EXECUTE format('SELECT EXISTS (
            SELECT FROM %I.grant_catalog_document_ownership WHERE document_id = $1 AND incarnation = $2
        )', TG_TABLE_SCHEMA) INTO owns_incarnation USING NEW.id, COALESCE(NEW.incarnation, NEW.id);
        IF owns_incarnation THEN
            RETURN NEW;
        END IF;
    END IF;
    RAISE check_violation USING MESSAGE = 'invalid document assignment marker';
END;
$$;

CREATE TRIGGER grant_catalog_guard_insert BEFORE INSERT ON documents
    FOR EACH ROW WHEN (NEW.grant_catalog_assigned)
    EXECUTE FUNCTION grant_catalog_guard_assignment_marker();

CREATE TRIGGER grant_catalog_guard_update BEFORE UPDATE OF grant_catalog_assigned ON documents
    FOR EACH ROW WHEN (OLD.grant_catalog_assigned IS DISTINCT FROM NEW.grant_catalog_assigned)
    EXECUTE FUNCTION grant_catalog_guard_assignment_marker();

CREATE FUNCTION grant_catalog_cleanup_document() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    EXECUTE format('DELETE FROM %I.grant_catalog_document_ownership WHERE document_id = $1 AND incarnation = $2', TG_TABLE_SCHEMA)
    USING OLD.id, COALESCE(OLD.incarnation, OLD.id);
    RETURN OLD;
END;
$$;

CREATE TRIGGER grant_catalog_cleanup_document AFTER DELETE ON documents
    FOR EACH ROW WHEN (OLD.grant_catalog_assigned)
    EXECUTE FUNCTION grant_catalog_cleanup_document();

CREATE FUNCTION grant_catalog_guard_truncate() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    assigned BOOLEAN;
BEGIN
    EXECUTE format('SELECT EXISTS (SELECT FROM %I.grant_catalog_document_ownership)', TG_TABLE_SCHEMA) INTO assigned;
    IF assigned THEN
        RAISE check_violation USING MESSAGE = 'delete assigned documents before truncating';
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER grant_catalog_guard_truncate BEFORE TRUNCATE ON documents
    FOR EACH STATEMENT EXECUTE FUNCTION grant_catalog_guard_truncate();

CREATE FUNCTION grant_catalog_record_ownership_deletion() RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE
    next_revision BIGINT;
BEGIN
    EXECUTE format('UPDATE %I.grant_catalog_policy_revision SET revision = revision + 1 RETURNING revision', TG_TABLE_SCHEMA)
    INTO STRICT next_revision;
    EXECUTE format('INSERT INTO %I.grant_catalog_policy_audit (revision, operator, document_id, incarnation)
        VALUES ($1, session_user, $2, $3)', TG_TABLE_SCHEMA)
    USING next_revision, OLD.document_id, OLD.incarnation;
    RETURN OLD;
END;
$$;

CREATE TRIGGER record_ownership_deletion AFTER DELETE ON grant_catalog_document_ownership
    FOR EACH ROW EXECUTE FUNCTION grant_catalog_record_ownership_deletion();

CREATE VIEW grant_catalog_active_principals AS
SELECT tenant_id, principal_id, issuer, subject FROM grant_catalog_principals WHERE enabled;

CREATE VIEW grant_catalog_collection_creators AS
SELECT p.tenant_id, p.principal_id, p.collection
FROM grant_catalog_create_permissions p
JOIN grant_catalog_active_principals a USING (tenant_id, principal_id)
WHERE p.can_create;

CREATE VIEW grant_catalog_document_access AS
WITH rights AS (
    SELECT tenant_id, document_id, incarnation, principal_id, TRUE AS is_owner, TRUE AS can_download
    FROM grant_catalog_document_ownership
    UNION ALL
    SELECT tenant_id, document_id, incarnation, principal_id, FALSE, can_download
    FROM grant_catalog_document_grants WHERE can_read
)
SELECT o.tenant_id, r.principal_id, o.document_id, o.incarnation, o.collection, TRUE AS can_read,
       bool_or(r.can_download) AS can_download, bool_or(r.is_owner) AS is_owner
FROM rights r
JOIN grant_catalog_active_principals p USING (tenant_id, principal_id)
JOIN grant_catalog_document_ownership o USING (tenant_id, document_id, incarnation)
JOIN documents d ON d.id = o.document_id AND COALESCE(d.incarnation, d.id) = o.incarnation
    AND d.collection = o.collection AND d.grant_catalog_assigned
WHERE o.ready
GROUP BY o.tenant_id, r.principal_id, o.document_id, o.incarnation, o.collection;

-- Bind the installed documents relation without resolving names through a caller's search path.
CREATE VIEW grant_catalog_source_documents AS
SELECT d.id AS document_id, COALESCE(d.incarnation, d.id) AS incarnation, d.collection,
       encode(sha256(convert_to((to_jsonb(d) - 'grant_catalog_assigned')::text, 'UTF8')), 'hex') AS source_version
FROM documents d;

CREATE FUNCTION grant_catalog_source_snapshot(p_document_id UUID)
RETURNS TABLE (document_id UUID, incarnation UUID, collection TEXT, source_version TEXT)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, pg_temp SET timezone = 'UTC' SET datestyle = 'ISO, YMD'
BEGIN ATOMIC
    SELECT d.document_id, d.incarnation, d.collection, d.source_version
    FROM grant_catalog_source_documents d WHERE d.document_id = p_document_id;
END;

