        '{[1,31],[127,159],[173,173],[1536,1541],[1564,1564],[1757,1757],[1807,1807],[2192,2193],[2274,2274],[6158,6158],[8203,8207],[8234,8238],[8288,8292],[8294,8303],[65279,65279],[65529,65531],[69821,69821],[69837,69837],[78896,78911],[113824,113827],[119155,119162],[917505,917505],[917536,917631]}';
    data JSONB;
    runes JSONB;
    pairs JSONB;
    properties JSONB;
    original INTEGER[];
    decomposed INTEGER[] := '{}';
    composed INTEGER[] := '{}';
    cp INTEGER;
    leading_count INTEGER;
    trailing_count INTEGER;
    nonstarters INTEGER := 0;
    syllable INTEGER;
    ccc INTEGER;
    previous_ccc INTEGER := 0;
    starter INTEGER;
    starter_position INTEGER;
    combined INTEGER;
BEGIN
    IF getdatabaseencoding() <> 'UTF8' THEN
        RETURN FALSE;
    END IF;
    IF ascii(left(label, 1)) <@ whitespace OR ascii(right(label, 1)) <@ whitespace THEN
        RETURN FALSE;
    END IF;
    SELECT coalesce(array_agg(ascii(character) ORDER BY i),'{}') INTO original
    FROM string_to_table(label, NULL) WITH ORDINALITY AS characters(character, i);
    IF EXISTS (SELECT FROM unnest(original) AS codepoint WHERE codepoint <@ prohibited) THEN
        RETURN FALSE;
    END IF;
    IF octet_length(label) = char_length(label) THEN
        RETURN TRUE;
    END IF;
    data := grant_catalog_unicode_data();
    runes := data->'runes';
    pairs := data->'pairs';
    FOREACH cp IN ARRAY original LOOP
        IF cp >= 44032 AND cp < 55204 THEN
            -- Split a Hangul syllable into its leading, vowel and optional trailing Jamo.
            syllable := cp - 44032;
            leading_count := 0;
            trailing_count := 1 + (syllable % 28 <> 0)::INTEGER;
            decomposed := decomposed || ARRAY[4352 + syllable / 588, 4449 + (syllable % 588) / 28];
            IF trailing_count = 2 THEN
                decomposed := array_append(decomposed, 4519 + syllable % 28);
            END IF;
        ELSE
            properties := runes->cp::TEXT;
            leading_count := coalesce((properties->>1)::INTEGER, 0);
            trailing_count := coalesce((properties->>2)::INTEGER, 0);
            IF jsonb_array_length(properties) > 3 THEN
                decomposed := decomposed || ARRAY(
                    SELECT value::INTEGER FROM jsonb_array_elements_text(properties) WITH ORDINALITY
                    WHERE ordinality > 3 ORDER BY ordinality
                );
            ELSE
                decomposed := array_append(decomposed, cp);
            END IF;
        END IF;
        -- The service inserts a combining grapheme joiner before overflow.
        IF nonstarters + leading_count > 30 THEN
            RETURN FALSE;
        END IF;
        nonstarters := CASE WHEN leading_count = 0 THEN trailing_count ELSE nonstarters + leading_count END;
    END LOOP;

    -- Stable canonical ordering within each segment headed by a starter.
    FOR cp, ccc IN
        SELECT part, class FROM (
            SELECT *, sum((class = 0)::INTEGER) OVER (ORDER BY i) AS segment FROM (
                SELECT part, i, coalesce((runes->part::TEXT->>0)::INTEGER, 0) AS class
                FROM unnest(decomposed) WITH ORDINALITY AS parts(part,i)
            ) classes
        ) segments ORDER BY segment, class, i
    LOOP
        combined := NULL;
        IF starter IS NOT NULL AND (previous_ccc = 0 OR previous_ccc < ccc) THEN
            IF starter >= 4352 AND starter < 4371 AND cp >= 4449 AND cp < 4470 THEN
                combined := 44032 + (starter - 4352) * 588 + (cp - 4449) * 28;
            ELSIF starter >= 44032 AND starter < 55204 AND (starter - 44032) % 28 = 0 AND cp > 4519 AND cp < 4547 THEN
                combined := starter + cp - 4519;
            ELSE
                combined := (pairs->>format('%s,%s',starter,cp))::INTEGER;
            END IF;
        END IF;
        IF combined IS NOT NULL THEN
            composed[starter_position] := combined;
            starter := combined;
        ELSE
            composed := array_append(composed, cp);
            previous_ccc := ccc;
            IF ccc = 0 THEN
                starter := cp;
                starter_position := cardinality(composed);
            END IF;
        END IF;
    END LOOP;
    RETURN composed = original;
END;
$$;

CREATE FUNCTION grant_catalog_decode_import(raw TEXT) RETURNS JSONB
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    batch JSON;
BEGIN
    IF raw IS NULL THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid batch JSON';
    END IF;
    IF octet_length(raw) > 262144 THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'batch exceeds 262144 bytes';
    END IF;
    batch := raw::JSON;
    IF json_typeof(batch) <> 'object' THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid batch JSON';
    END IF;
    IF EXISTS (SELECT 1 FROM json_each(batch) GROUP BY key COLLATE "C" HAVING count(*) > 1) THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'duplicate batch field';
    END IF;
    IF json_typeof(batch->'expected_revision') IS DISTINCT FROM 'number'
       OR (batch->>'expected_revision') !~ '^(-0|0|[1-9][0-9]*)$' THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid batch header';
    END IF;
    IF EXISTS (
        SELECT 1 FROM json_each(batch) AS groups
        CROSS JOIN LATERAL json_array_elements(
            CASE WHEN json_typeof(groups.value) = 'array' THEN groups.value ELSE '[]'::JSON END
        ) AS entry
        WHERE EXISTS (
            SELECT 1 FROM json_each(
                CASE WHEN json_typeof(entry.value) = 'object' THEN entry.value ELSE '{}'::JSON END
            ) GROUP BY key COLLATE "C" HAVING count(*) > 1
        )
    ) THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'duplicate entry field';
    END IF;
    RETURN batch::JSONB;
EXCEPTION WHEN data_exception THEN
    RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid batch JSON';
END;
$$;

CREATE FUNCTION grant_catalog_parse_import(p_payload JSONB) RETURNS grant_catalog_import_entry[]
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    group_name TEXT;
    group_value JSONB;
    item JSONB;
    field TEXT;
    fields TEXT[];
    entry grant_catalog_import_entry;
    entries grant_catalog_import_entry[] := '{}';
    invalid CONSTANT TEXT := 'invalid batch entries';
BEGIN
    FOR group_name, group_value IN SELECT * FROM jsonb_each(p_payload - 'batch_id' - 'expected_revision')
    LOOP
        fields := CASE group_name
            WHEN 'tenants' THEN ARRAY['tenant_id']
            WHEN 'principals' THEN ARRAY['tenant_id', 'principal_id', 'issuer', 'subject', 'enabled']
            WHEN 'collections' THEN ARRAY['tenant_id', 'collection']
            WHEN 'create_permissions' THEN ARRAY['tenant_id', 'principal_id', 'collection', 'can_create']
            WHEN 'assignments' THEN ARRAY['tenant_id', 'principal_id', 'collection', 'document_id', 'source_version']
            WHEN 'grants' THEN ARRAY['tenant_id', 'principal_id', 'document_id', 'incarnation', 'can_read', 'can_download']
            WHEN 'reservations' THEN ARRAY['tenant_id', 'principal_id', 'collection', 'document_id']
        END;
        IF fields IS NULL OR jsonb_typeof(group_value) <> 'array' THEN
            RAISE SQLSTATE 'QG001' USING MESSAGE = invalid;
        END IF;
        IF cardinality(entries) + jsonb_array_length(group_value) > 500 THEN
            RAISE SQLSTATE 'QG001' USING MESSAGE = 'batch exceeds 500 entries';
        END IF;
        FOR item IN SELECT value FROM jsonb_array_elements(group_value)
        LOOP
            IF jsonb_typeof(item) <> 'object' OR item - fields <> '{}'::jsonb OR NOT item ?& fields THEN
                RAISE SQLSTATE 'QG001' USING MESSAGE = invalid;
            END IF;
            FOREACH field IN ARRAY fields
            LOOP
                IF NOT (CASE
                    WHEN field IN ('enabled', 'can_create', 'can_read', 'can_download')
                        THEN jsonb_typeof(item->field) = 'boolean'
                    WHEN jsonb_typeof(item->field) <> 'string' THEN FALSE
                    WHEN field = 'collection' THEN octet_length(item->>field) <= 128
                    WHEN field IN ('issuer', 'subject') THEN octet_length(item->>field) BETWEEN 1 AND 1024
                    WHEN field = 'source_version' THEN item->>field ~ '^[0-9a-f]{64}$'
                    ELSE item->>field ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
                        AND item->>field <> '00000000-0000-0000-0000-000000000000'
                END) THEN
                    RAISE SQLSTATE 'QG001' USING MESSAGE = invalid;
                END IF;
            END LOOP;
            entry := jsonb_populate_record(NULL::grant_catalog_import_entry, item);
            IF group_name IN ('create_permissions', 'reservations')
               AND NOT grant_catalog_eligible_collection(entry.collection) THEN
                RAISE SQLSTATE 'QG001' USING MESSAGE = 'collection must be a canonical service label';
            END IF;
            entry.entry_group := group_name;
            entries := array_append(entries, entry);
        END LOOP;
    END LOOP;
    IF cardinality(entries) = 0 THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'batch requires at least one entry';
    END IF;
    IF EXISTS (
        SELECT 1 FROM unnest(entries) e
        GROUP BY entry_group, principal_id, document_id,
                 CASE WHEN entry_group IN ('tenants', 'collections') THEN tenant_id END,
                 CASE WHEN entry_group IN ('collections', 'create_permissions') THEN collection COLLATE "C" END
        HAVING count(*) > 1
    ) OR EXISTS (
        SELECT 1 FROM unnest(entries) WHERE entry_group IN ('assignments', 'reservations')
        GROUP BY document_id HAVING count(*) > 1
    ) OR EXISTS (
        SELECT 1 FROM unnest(entries) WHERE entry_group = 'principals'
        GROUP BY issuer COLLATE "C", subject COLLATE "C" HAVING count(*) > 1
    ) THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'duplicate batch target';
    END IF;
    RETURN entries;
END;
$$;

CREATE FUNCTION grant_catalog_validate_import(entries grant_catalog_import_entry[]) RETURNS VOID
LANGUAGE plpgsql STABLE AS $$
DECLARE
    bad_group TEXT;
BEGIN
    WITH proposed_tenants AS (
        SELECT tenant_id FROM grant_catalog_tenants
        UNION ALL SELECT tenant_id FROM unnest(entries) WHERE entry_group = 'tenants'
    ), proposed_principals AS (
        SELECT principal_id, tenant_id, enabled FROM unnest(entries) WHERE entry_group = 'principals'
        UNION ALL
        SELECT p.principal_id, p.tenant_id, p.enabled FROM grant_catalog_principals p
        WHERE NOT EXISTS (SELECT 1 FROM unnest(entries) e WHERE e.entry_group = 'principals' AND e.principal_id = p.principal_id)
    ), proposed_collections AS (
        SELECT tenant_id, collection FROM grant_catalog_collections
        UNION ALL SELECT tenant_id, collection FROM unnest(entries) WHERE entry_group = 'collections'
    ), proposed_ownership AS (
        SELECT tenant_id, document_id, incarnation FROM grant_catalog_document_ownership
        UNION ALL
        SELECT e.tenant_id, e.document_id, d.incarnation FROM unnest(entries) e
        JOIN grant_catalog_source_documents d USING (document_id) WHERE e.entry_group = 'assignments'
    )
    SELECT e.entry_group INTO bad_group FROM unnest(entries) e
    WHERE (e.entry_group <> 'tenants' AND NOT EXISTS (
        SELECT 1 FROM proposed_tenants t WHERE t.tenant_id = e.tenant_id
    )) OR (e.entry_group NOT IN ('tenants', 'principals', 'collections') AND NOT EXISTS (
        SELECT 1 FROM proposed_principals p WHERE (p.tenant_id, p.principal_id) = (e.tenant_id, e.principal_id)
        AND (e.entry_group NOT IN ('assignments', 'reservations') OR p.enabled)
    )) OR (e.entry_group IN ('assignments', 'create_permissions', 'reservations') AND NOT EXISTS (
        SELECT 1 FROM proposed_collections c WHERE (c.tenant_id, c.collection) = (e.tenant_id, e.collection)
    )) OR (e.entry_group = 'principals' AND EXISTS (
        SELECT 1 FROM grant_catalog_principals p
        WHERE (p.principal_id = e.principal_id OR (p.issuer, p.subject) = (e.issuer, e.subject))
          AND (p.principal_id, p.tenant_id, p.issuer, p.subject) <> (e.principal_id, e.tenant_id, e.issuer, e.subject)
    )) OR (e.entry_group = 'assignments' AND NOT EXISTS (
        SELECT 1 FROM grant_catalog_source_documents d
        LEFT JOIN grant_catalog_document_ownership o USING (document_id)
        LEFT JOIN grant_catalog_assigned_incarnations i
          ON (i.document_id, i.incarnation) = (d.document_id, d.incarnation)
        LEFT JOIN grant_catalog_document_reservations r
          ON (r.document_id, r.incarnation) = (d.document_id, d.incarnation) AND r.state = 'pending'
        WHERE d.document_id = e.document_id AND d.collection COLLATE "C" = e.collection
          AND d.source_version = e.source_version
          AND (r.document_id IS NULL OR (r.tenant_id, r.principal_id, r.collection) =
               (e.tenant_id, e.principal_id, e.collection))
          AND (((o.tenant_id, o.principal_id, o.incarnation) = (e.tenant_id, e.principal_id, d.incarnation)
                AND (NOT o.ready OR (o.collection, o.source_version) = (e.collection, e.source_version)))
               OR (o.document_id IS NULL AND i.document_id IS NULL))
    )) OR (e.entry_group = 'grants' AND (e.can_download AND NOT e.can_read OR NOT EXISTS (
        SELECT 1 FROM proposed_ownership o
        WHERE (o.tenant_id, o.document_id, o.incarnation) = (e.tenant_id, e.document_id, e.incarnation)
    ))) OR (e.entry_group = 'reservations' AND (
        EXISTS (SELECT 1 FROM grant_catalog_source_documents d WHERE d.document_id = e.document_id)
        OR EXISTS (SELECT 1 FROM grant_catalog_assigned_incarnations i WHERE i.document_id = e.document_id)
        OR EXISTS (SELECT 1 FROM grant_catalog_document_reservations r WHERE r.document_id = e.document_id)
    ))
    LIMIT 1;
    IF FOUND THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid or conflicting ' || bad_group || ' entry';
    END IF;
END;
$$;

CREATE FUNCTION grant_catalog_apply_import(entries grant_catalog_import_entry[]) RETURNS VOID
LANGUAGE sql AS $$
    INSERT INTO grant_catalog_tenants (tenant_id)
    SELECT tenant_id FROM unnest(entries) WHERE entry_group = 'tenants' ON CONFLICT DO NOTHING;

    INSERT INTO grant_catalog_principals (principal_id, tenant_id, issuer, subject, enabled)
    SELECT principal_id, tenant_id, issuer, subject, enabled FROM unnest(entries) WHERE entry_group = 'principals'
    ON CONFLICT (principal_id) DO UPDATE SET enabled = excluded.enabled;

    INSERT INTO grant_catalog_collections (tenant_id, collection)
    SELECT tenant_id, collection FROM unnest(entries) WHERE entry_group = 'collections' ON CONFLICT DO NOTHING;

    INSERT INTO grant_catalog_create_permissions (tenant_id, principal_id, collection, can_create)
    SELECT tenant_id, principal_id, collection, can_create FROM unnest(entries) WHERE entry_group = 'create_permissions'
    ON CONFLICT (tenant_id, principal_id, collection) DO UPDATE SET can_create = excluded.can_create;

    INSERT INTO grant_catalog_assigned_incarnations (document_id, incarnation)
    SELECT d.document_id, d.incarnation FROM unnest(entries) e
    JOIN grant_catalog_source_documents d USING (document_id) WHERE e.entry_group = 'assignments'
    ON CONFLICT DO NOTHING;

    INSERT INTO grant_catalog_document_ownership AS o (document_id, incarnation, tenant_id, principal_id, collection, source_version)
    SELECT d.document_id, d.incarnation, e.tenant_id, e.principal_id, e.collection, e.source_version
    FROM unnest(entries) e JOIN grant_catalog_source_documents d USING (document_id)
    WHERE e.entry_group = 'assignments'
    ON CONFLICT (document_id) DO UPDATE SET collection = excluded.collection, source_version = excluded.source_version
    WHERE NOT o.ready AND (o.collection, o.source_version) IS DISTINCT FROM (excluded.collection, excluded.source_version);

    UPDATE documents d SET grant_catalog_assigned = TRUE
    FROM unnest(entries) e
    WHERE e.entry_group = 'assignments' AND d.id = e.document_id AND NOT d.grant_catalog_assigned;

    UPDATE grant_catalog_document_reservations r
    SET state = CASE WHEN r.incarnation = d.incarnation THEN 'spent' ELSE 'superseded' END
    FROM unnest(entries) e JOIN grant_catalog_source_documents d USING (document_id)
    WHERE e.entry_group = 'assignments' AND r.document_id = e.document_id AND r.state = 'pending'
      AND (r.incarnation <> d.incarnation OR (r.tenant_id, r.principal_id, r.collection) =
           (e.tenant_id, e.principal_id, e.collection));

    INSERT INTO grant_catalog_document_grants (tenant_id, document_id, incarnation, principal_id, can_read, can_download)
    SELECT tenant_id, document_id, incarnation, principal_id, can_read, can_download FROM unnest(entries)
    WHERE entry_group = 'grants' AND can_read
    ON CONFLICT (tenant_id, document_id, incarnation, principal_id) DO UPDATE
    SET can_download = excluded.can_download;

    DELETE FROM grant_catalog_document_grants g USING unnest(entries) e
    WHERE e.entry_group = 'grants' AND NOT e.can_read AND
        (g.tenant_id, g.document_id, g.incarnation, g.principal_id) =
        (e.tenant_id, e.document_id, e.incarnation, e.principal_id);

    INSERT INTO grant_catalog_document_reservations (document_id, tenant_id, principal_id, collection)
    SELECT document_id, tenant_id, principal_id, collection FROM unnest(entries) WHERE entry_group = 'reservations';
$$;

CREATE FUNCTION grant_catalog_committed_revision(batch UUID, digest BYTEA) RETURNS BIGINT
LANGUAGE plpgsql STABLE AS $$
DECLARE
    saved grant_catalog_policy_audit%ROWTYPE;
BEGIN
    SELECT a.* INTO saved FROM grant_catalog_policy_audit a WHERE a.batch_id = batch;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    IF saved.operator <> session_user OR saved.payload_hash <> digest THEN
        RAISE SQLSTATE 'QG002' USING MESSAGE = 'batch ID conflict';
    END IF;
    RETURN saved.revision;
END;
$$;

CREATE FUNCTION grant_catalog_enter(anchor REGCLASS) RETURNS VOID
LANGUAGE plpgsql AS $$
DECLARE
    scope pg_namespace%ROWTYPE;
BEGIN
    SELECT n.* INTO STRICT scope FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = anchor;
    IF EXISTS (
        SELECT FROM aclexplode(coalesce(scope.nspacl, acldefault('n', scope.nspowner))) acl
        WHERE acl.privilege_type = 'CREATE' AND acl.grantee <> scope.nspowner
    ) THEN
        RAISE SQLSTATE 'QG005' USING MESSAGE = 'catalog schema must restrict CREATE to its owner';
    END IF;
    PERFORM set_config('search_path', format('pg_catalog, %I, pg_temp', scope.nspname), true);
END;
$$;

CREATE FUNCTION grant_catalog_import_header(p_payload JSONB)
RETURNS TABLE (batch UUID, expected BIGINT, payload_hash BYTEA)
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF jsonb_typeof(p_payload->'batch_id') IS DISTINCT FROM 'string'
       OR jsonb_typeof(p_payload->'expected_revision') IS DISTINCT FROM 'number'
       OR p_payload->>'expected_revision' !~ '^[0-9]+$'
       OR p_payload->>'batch_id' !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       OR p_payload->>'batch_id' = '00000000-0000-0000-0000-000000000000' THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid batch header';
    END IF;
    RETURN QUERY SELECT (p_payload->>'batch_id')::UUID, (p_payload->>'expected_revision')::BIGINT,
        sha256(convert_to(p_payload::text, 'UTF8'));
END;
$$;

CREATE FUNCTION grant_catalog_check_revision(current_revision BIGINT, expected BIGINT) RETURNS VOID
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF current_revision <> expected THEN
        RAISE SQLSTATE 'QG003' USING MESSAGE = 'stale revision';
    END IF;
    IF current_revision = 9223372036854775807 THEN
        RAISE SQLSTATE 'QG004' USING MESSAGE = 'revision exhausted';
    END IF;
END;
$$;

-- STABLE keeps the receipt, revision and reference checks on one command snapshot.
CREATE FUNCTION grant_catalog_preview(p_payload JSONB)
RETURNS TABLE (resulting_revision BIGINT, replayed BOOLEAN)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    batch UUID;
    expected BIGINT;
    payload_hash BYTEA;
    saved_revision BIGINT;
    current_revision BIGINT;
BEGIN
    SELECT h.batch, h.expected, h.payload_hash INTO STRICT batch, expected, payload_hash
    FROM grant_catalog_import_header(p_payload) h;
    saved_revision := grant_catalog_committed_revision(batch, payload_hash);
    IF saved_revision IS NOT NULL THEN
        RETURN QUERY SELECT saved_revision, TRUE;
        RETURN;
    END IF;
    SELECT revision INTO STRICT current_revision FROM grant_catalog_policy_revision;
    PERFORM grant_catalog_check_revision(current_revision, expected);
    PERFORM grant_catalog_validate_import(grant_catalog_parse_import(p_payload));
    RETURN QUERY SELECT current_revision, FALSE;
END;
$$;

CREATE FUNCTION grant_catalog_import_impl(p_raw TEXT, p_dry_run BOOLEAN)
RETURNS TABLE (resulting_revision BIGINT, replayed BOOLEAN)
LANGUAGE plpgsql AS $$
DECLARE
    p_payload JSONB;
    batch UUID;
    expected BIGINT;
    payload_hash BYTEA;
    saved_revision BIGINT;
    entries grant_catalog_import_entry[];
    current_revision BIGINT;
BEGIN
    IF p_dry_run IS NULL THEN
        RAISE SQLSTATE 'QG001' USING MESSAGE = 'invalid preview flag';
    END IF;
    p_payload := grant_catalog_decode_import(p_raw);
    IF p_dry_run THEN
        RETURN QUERY SELECT * FROM grant_catalog_preview(p_payload);
        RETURN;
    END IF;
    SELECT h.batch, h.expected, h.payload_hash INTO STRICT batch, expected, payload_hash
    FROM grant_catalog_import_header(p_payload) h;
    saved_revision := grant_catalog_committed_revision(batch, payload_hash);
    IF saved_revision IS NOT NULL THEN
        RETURN QUERY SELECT saved_revision, TRUE;
        RETURN;
    END IF;
    entries := grant_catalog_parse_import(p_payload);

    -- Document deletion locks its source row before removing ownership and advancing policy.
    PERFORM d.document_id FROM grant_catalog_source_documents d
    WHERE d.document_id IN (SELECT e.document_id FROM unnest(entries) e WHERE e.entry_group IN ('assignments', 'grants'))
    ORDER BY d.document_id FOR NO KEY UPDATE;
    SELECT revision INTO STRICT current_revision FROM grant_catalog_policy_revision FOR UPDATE;
    saved_revision := grant_catalog_committed_revision(batch, payload_hash);
    IF saved_revision IS NOT NULL THEN
        RETURN QUERY SELECT saved_revision, TRUE;
        RETURN;
    END IF;
    PERFORM grant_catalog_check_revision(current_revision, expected);
    PERFORM grant_catalog_validate_import(entries);

    PERFORM grant_catalog_apply_import(entries);
    UPDATE grant_catalog_policy_revision SET revision = revision + 1 RETURNING revision INTO STRICT current_revision;
    INSERT INTO grant_catalog_policy_audit (revision, operator, batch_id, payload_hash)
    VALUES (current_revision, session_user, batch, payload_hash);
    RETURN QUERY SELECT current_revision, FALSE;
END;
$$;

-- SQL-standard bodies bind dependencies at creation. The regclass anchor
-- follows its corpus through renames and prevents the old name from being reused.
CREATE FUNCTION grant_catalog_import_batch(p_raw TEXT, p_dry_run BOOLEAN)
RETURNS TABLE (resulting_revision BIGINT, replayed BOOLEAN)
LANGUAGE sql SECURITY DEFINER
SET search_path = pg_catalog, pg_temp SET timezone = 'UTC' SET datestyle = 'ISO, YMD'
BEGIN ATOMIC
    SELECT grant_catalog_enter('grant_catalog_policy_revision'::regclass);
    SELECT * FROM grant_catalog_import_impl(p_raw, p_dry_run);
END;

-- Remove both PUBLIC access and named default grants inherited from the object creator.
DO $$
DECLARE
    catalog_schema NAME := current_schema();
    catalog_namespace OID;
    permission RECORD;
BEGIN
    SELECT oid INTO STRICT catalog_namespace FROM pg_namespace WHERE nspname = catalog_schema;
    FOR permission IN
        SELECT 'TABLE' AS kind, format('%I.%I', catalog_schema, c.relname) AS identity, acl.grantee
        FROM pg_class c CROSS JOIN LATERAL aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) acl
        WHERE c.relnamespace = catalog_namespace AND c.oid IN (
            'grant_catalog_policy_revision'::regclass, 'grant_catalog_tenants'::regclass,
            'grant_catalog_principals'::regclass, 'grant_catalog_collections'::regclass,
            'grant_catalog_create_permissions'::regclass, 'grant_catalog_assigned_incarnations'::regclass,
            'grant_catalog_document_ownership'::regclass, 'grant_catalog_document_grants'::regclass,
            'grant_catalog_document_reservations'::regclass, 'grant_catalog_policy_audit'::regclass,
            'grant_catalog_active_principals'::regclass, 'grant_catalog_collection_creators'::regclass,
            'grant_catalog_document_access'::regclass, 'grant_catalog_source_documents'::regclass
        ) AND acl.grantee <> c.relowner
        UNION ALL
        SELECT 'FUNCTION', format('%I.%I(%s)', catalog_schema, p.proname, pg_get_function_identity_arguments(p.oid)), acl.grantee
        FROM pg_proc p CROSS JOIN LATERAL aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) acl
        WHERE p.pronamespace = catalog_namespace AND p.oid IN (
            'grant_catalog_keep_document_identity()'::regprocedure,
            'grant_catalog_guard_assignment_marker()'::regprocedure, 'grant_catalog_cleanup_document()'::regprocedure,
            'grant_catalog_guard_truncate()'::regprocedure, 'grant_catalog_record_ownership_deletion()'::regprocedure,
            'grant_catalog_source_snapshot(uuid)'::regprocedure, 'grant_catalog_eligible_collection(text)'::regprocedure,
            'grant_catalog_unicode_data()'::regprocedure, 'grant_catalog_decode_import(text)'::regprocedure,
            'grant_catalog_parse_import(jsonb)'::regprocedure, 'grant_catalog_validate_import(grant_catalog_import_entry[])'::regprocedure,
            'grant_catalog_apply_import(grant_catalog_import_entry[])'::regprocedure, 'grant_catalog_committed_revision(uuid,bytea)'::regprocedure,
            'grant_catalog_enter(regclass)'::regprocedure, 'grant_catalog_import_header(jsonb)'::regprocedure,
            'grant_catalog_check_revision(bigint,bigint)'::regprocedure, 'grant_catalog_preview(jsonb)'::regprocedure,
            'grant_catalog_import_impl(text,boolean)'::regprocedure, 'grant_catalog_import_batch(text,boolean)'::regprocedure
        ) AND acl.grantee <> p.proowner
        UNION ALL
        SELECT 'TYPE', format('%I.%I', catalog_schema, t.typname), acl.grantee
        FROM pg_type t CROSS JOIN LATERAL aclexplode(coalesce(t.typacl, acldefault('T', t.typowner))) acl
        WHERE t.typnamespace = catalog_namespace
          AND t.typname = 'grant_catalog_import_entry' AND acl.grantee <> t.typowner
    LOOP
        EXECUTE format('REVOKE ALL PRIVILEGES ON %s %s FROM %s CASCADE',
            permission.kind, permission.identity,
            CASE WHEN permission.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(pg_get_userbyid(permission.grantee)) END);
    END LOOP;
END;
$$;
